"""Константы интеграции Ufanet Door Phone."""

DOMAIN = "hekus_doorphone"
NAME = "Hekus DoorPhone"

CONF_USERNAME = "username"
CONF_PASSWORD = "password"

# Домофоны, исключённые пользователем: после удаления устройства из реестра
# Home Assistant интеграция не создаёт его заново. Список пополняется только
# вручную — при удалении устройства или снятии галочки в опциях.
CONF_EXCLUDED_INTERCOMS = "excluded_intercoms"

# Поле формы опций: какие домофоны подключать к Home Assistant
CONF_ENABLED_INTERCOMS = "enabled_intercoms"

# Интервал опроса списка домофонов, в секундах
DEFAULT_SCAN_INTERVAL = 300

# Время, в течение которого дверь нельзя открыть повторно, в секундах
UNLOCK_COOLDOWN = 8

# Интервал опроса истории вызовов, в секундах. Меньше интервала опроса
# домофонов, чтобы звонок попадал в Home Assistant с небольшой задержкой.
CALL_HISTORY_SCAN_INTERVAL = 300

# Сколько последних вызовов запрашивать из истории. Страница одна на весь
# договор: API не умеет фильтровать историю по камере, поэтому вызовы
# распределяются по домофонам уже в интеграции.
CALL_HISTORY_PAGE_SIZE = 30

# Сколько раз пытаться получить ссылки на запись звонка: запись и превью
# появляются не сразу после вызова
CALL_HISTORY_LINK_ATTEMPTS = 3

# Таймаут извлечения кадра превью ffmpeg'ом, в секундах. Home Assistant сам
# ограничивает получение изображения сущности image десятью секундами, поэтому
# таймаут должен быть меньше.
CALL_PREVIEW_TIMEOUT = 8

# Пауза между неудачными попытками получить кадр превью, в секундах
CALL_PREVIEW_RETRY_SECONDS = 30

# Максимальный размер кадра превью, байт: защита от неожиданно большого ответа
CALL_PREVIEW_MAX_BYTES = 8 * 1024 * 1024

